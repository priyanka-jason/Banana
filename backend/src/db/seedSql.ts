import type { FinalItem, StoreRecord } from '../pipeline/types';
import type { Chain, StoreLocation } from '../types';
import { rawTableName } from './storeData';

/**
 * Turns pipeline output into one SQL script that loads it into the Supabase tables from
 * sql/supabase-setup.sql: the per-store rows into raw.<chain>, and chains, stores, products
 * and prices into banana. Paste the script into the Supabase SQL Editor and run it.
 *
 * It is one transaction (all or nothing) and safe to run again: rows that already exist
 * are updated, not duplicated. It never deletes anything.
 *
 * This is a stopgap that needs no database password. The long-term way is a backend
 * command that writes through a database connection.
 */

export interface SeedData {
  chains: Chain[];
  locations: StoreLocation[];
  /** Per-store rows, as saved in the per-store layer. */
  records: StoreRecord[];
  /** Final items, from the combine step. */
  items: FinalItem[];
  /** A line for the top of the file saying what this is. */
  title: string;
}

/** A SQL text value. Doubling single quotes is all standard_conforming_strings needs; null bytes are refused. */
export function sqlText(value: string | undefined | null): string {
  if (value === undefined || value === null) return 'null';
  if (value.includes('\u0000')) throw new Error('Text with a null byte cannot be stored');
  return `'${value.replaceAll("'", "''")}'`;
}

function sqlNumber(value: number | undefined): string {
  if (value === undefined) return 'null';
  if (!Number.isFinite(value)) throw new Error(`Not a finite number: ${value}`);
  return String(value);
}

function sqlInteger(value: number | undefined): string {
  if (value !== undefined && !Number.isInteger(value)) throw new Error(`Not a whole number: ${value}`);
  return sqlNumber(value);
}

const sqlBool = (value: boolean): string => (value ? 'true' : 'false');
const sqlJson = (value: unknown): string => (value === undefined ? 'null' : `${sqlText(JSON.stringify(value))}::jsonb`);
const sqlTextArray = (values: string[]): string => (values.length === 0 ? `'{}'::text[]` : `array[${values.map(sqlText).join(', ')}]::text[]`);
const sqlDate = (value: string | undefined): string => (value === undefined ? 'null' : `${sqlText(value)}::date`);
const sqlTime = (value: string): string => `${sqlText(value)}::timestamptz`;

function rows(lines: string[]): string {
  return lines.map((line) => `  (${line})`).join(',\n');
}

export function buildSeedSql(data: SeedData): string {
  const out: string[] = [];
  out.push(`-- ${data.title}`);
  out.push('-- Generated by `npm run seed-sql` in backend/. Do not edit by hand.');
  out.push('-- Run in the Supabase SQL Editor after sql/supabase-setup.sql. All or nothing; safe to run again.');
  out.push(
    `-- ${data.chains.length} chains, ${data.locations.length} stores, ${data.records.length} per-store rows, ${data.items.length} products and prices.`,
  );
  out.push('', 'begin;', '');

  // Per-store layer: one insert per chain table.
  const byChain = new Map<string, StoreRecord[]>();
  for (const record of data.records) byChain.set(record.chainSlug, [...(byChain.get(record.chainSlug) ?? []), record]);
  for (const [chainSlug, records] of [...byChain].sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`insert into ${rawTableName(chainSlug)} (sku, scraped_at, payload, original) values`);
    out.push(rows(records.map((r) => [sqlText(r.sku), sqlTime(r.scrapedAt), sqlJson(r.payload), sqlJson(r.original)].join(', '))));
    out.push('on conflict (sku) do update set');
    out.push('  scraped_at = excluded.scraped_at, payload = excluded.payload, original = excluded.original;', '');
  }

  // Final layer.
  out.push('insert into banana.chains (slug, name, parent_company, has_member_pricing) values');
  out.push(rows(data.chains.map((c) => [sqlText(c.slug), sqlText(c.name), sqlText(c.parentCompany), sqlBool(c.hasMemberPricing)].join(', '))));
  out.push('on conflict (slug) do update set');
  out.push('  name = excluded.name, parent_company = excluded.parent_company, has_member_pricing = excluded.has_member_pricing;', '');

  out.push('insert into banana.store_locations (id, chain_slug, name, address, city, postal_code, location) values');
  out.push(
    rows(
      data.locations.map((l) =>
        [
          sqlText(l.id),
          sqlText(l.chainSlug),
          sqlText(l.name),
          sqlText(l.address),
          sqlText(l.city),
          sqlText(l.postalCode),
          `extensions.st_setsrid(extensions.st_makepoint(${sqlNumber(l.lng)}, ${sqlNumber(l.lat)}), 4326)::extensions.geography`,
        ].join(', '),
      ),
    ),
  );
  out.push('on conflict (id) do update set');
  out.push('  chain_slug = excluded.chain_slug, name = excluded.name, address = excluded.address, city = excluded.city,');
  out.push('  postal_code = excluded.postal_code, location = excluded.location;', '');

  out.push(
    'insert into banana.products (chain_slug, sku, name, brand, size, pack_count, size_amount, size_unit, size_kind, size_total_base, priced_by_weight, upc, category, store_categories, image_url) values',
  );
  out.push(
    rows(
      data.items.map((i) =>
        [
          sqlText(i.chainSlug),
          sqlText(i.sku),
          sqlText(i.name),
          sqlText(i.brand),
          sqlText(i.size),
          sqlInteger(i.packCount),
          sqlNumber(i.sizeAmount),
          sqlText(i.sizeUnit),
          sqlText(i.sizeKind),
          sqlNumber(i.sizeTotalBase),
          sqlBool(i.pricedByWeight),
          sqlText(i.upc),
          sqlText(i.category),
          sqlTextArray(i.storeCategories),
          sqlText(i.imageUrl),
        ].join(', '),
      ),
    ),
  );
  out.push('on conflict (chain_slug, sku) do update set');
  out.push('  name = excluded.name, brand = excluded.brand, size = excluded.size, pack_count = excluded.pack_count,');
  out.push('  size_amount = excluded.size_amount, size_unit = excluded.size_unit, size_kind = excluded.size_kind,');
  out.push('  size_total_base = excluded.size_total_base, priced_by_weight = excluded.priced_by_weight, upc = excluded.upc,');
  out.push('  category = excluded.category, store_categories = excluded.store_categories, image_url = excluded.image_url;', '');

  // Prices point at products by their database id, so look each one up by chain and sku.
  out.push(
    'insert into banana.prices (product_id, location_id, regular_price_cents, sale_price_cents, member_price_cents, unit_price_cents, unit_label, sale_start, sale_end, source_url, scraped_at)',
  );
  out.push('select p.id, v.location_id, v.regular, v.sale, v.member, v.unit_price, v.unit_label, v.sale_start, v.sale_end, v.source_url, v.scraped_at');
  out.push('from (values');
  out.push(
    rows(
      data.items.map((i) =>
        [
          sqlText(i.chainSlug),
          sqlText(i.sku),
          i.locationId === undefined ? 'null::text' : sqlText(i.locationId),
          sqlInteger(i.regularPriceCents),
          `${sqlInteger(i.salePriceCents)}::integer`,
          `${sqlInteger(i.memberPriceCents)}::integer`,
          `${sqlInteger(i.unitPriceCents)}::integer`,
          `${sqlText(i.unitLabel)}::text`,
          sqlDate(i.saleStart),
          sqlDate(i.saleEnd),
          `${sqlText(i.sourceUrl)}::text`,
          sqlTime(i.scrapedAt),
        ].join(', '),
      ),
    ),
  );
  out.push(
    ') as v (chain_slug, sku, location_id, regular, sale, member, unit_price, unit_label, sale_start, sale_end, source_url, scraped_at)',
  );
  out.push('join banana.products p on p.chain_slug = v.chain_slug and p.sku = v.sku');
  out.push('on conflict (product_id, location_id) do update set');
  out.push('  regular_price_cents = excluded.regular_price_cents, sale_price_cents = excluded.sale_price_cents,');
  out.push('  member_price_cents = excluded.member_price_cents, unit_price_cents = excluded.unit_price_cents,');
  out.push('  unit_label = excluded.unit_label, sale_start = excluded.sale_start, sale_end = excluded.sale_end,');
  out.push('  source_url = excluded.source_url, scraped_at = excluded.scraped_at;', '');

  out.push('commit;', '');
  return out.join('\n');
}
